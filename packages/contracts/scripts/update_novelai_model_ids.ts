import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { extract_novelai_model_ids } from "../src/providers/novelai_models.js";

const IMAGE_PAGE_URL = "https://novelai.net/image";
const OUTPUT_PATH = fileURLToPath(
  new URL("../src/providers/novelai_model_ids.ts", import.meta.url),
);
const CHUNK_PATTERN = /\/_next\/static\/chunks\/[A-Za-z0-9._-]+\.js/gu;

async function fetch_text(url: string): Promise<string> {
  const response = await fetch(url, { headers: { "user-agent": "tavern-canvas-model-list" } });
  if (!response.ok) {
    throw new Error(`GET ${url} failed with ${String(response.status)}`);
  }
  return response.text();
}

const page = await fetch_text(IMAGE_PAGE_URL);
const chunk_urls = [...new Set(page.match(CHUNK_PATTERN) ?? [])].map(
  (path) => new URL(path, IMAGE_PAGE_URL).href,
);
if (chunk_urls.length === 0) {
  throw new Error("The NovelAI image page references no script chunks");
}
const sources = [page];
for (const url of chunk_urls) {
  sources.push(await fetch_text(url));
}
const model_ids = extract_novelai_model_ids(sources);
if (model_ids.length === 0) {
  throw new Error("No NovelAI model ids were found in the image page scripts");
}

const lines = model_ids.map((model_id) => `  "${model_id}",`).join("\n");
await writeFile(
  OUTPUT_PATH,
  `// Generated by packages/contracts/scripts/update_novelai_model_ids.ts from ${IMAGE_PAGE_URL}.\n` +
    `export const NOVELAI_PUBLISHED_MODEL_IDS: readonly string[] = [\n${lines}\n];\n`,
);
console.log(`Wrote ${String(model_ids.length)} model ids to ${OUTPUT_PATH}`);
